<?php declare(strict_types = 0);
/*
 * CPU/Memory 전체 사용률 추출 화면의 설정.
 *
 * 읽는 곳: includes/UsageExportService.php
 *         (화면: zabbix.php?action=usageexport.list   메뉴: 보고서 > CPU/Memory 전체 사용률 추출)
 *
 * ── 이 파일의 형식 ──
 *   실행되는 코드는 없다. "return [ ... ];" 로 배열 하나를 돌려주기만 한다.
 *   값을 고치면 다음 화면 조회부터 반영된다.
 *
 * ── 어느 아이템을 내보내는가 ──
 *   이 파일에는 아이템 키가 없다. 저사용/고사용 화면과 같은 설정을 쓴다.
 *     CPU    : conf/serverusage.conf.php 의 cpu_item_keys
 *     Memory : conf/serverusage.conf.php 의 memory_item_keys
 *   그 설정이 비어 있으면 이 화면에 "설정이 필요합니다" 안내가 나온다.
 *
 * 숫자는 모두 5버전 소스(monitoring.perf.view.php)와 화면 안내문에 있던 값이다.
 */

return [
	/*
	 * 한 번에 내보낼 수 있는 최대 기간(일).
	 * 5버전 화면 안내문: "실시간 Data 출력은 전일 ~ 3개월 기간 출력이 가능합니다"
	 * 3개월을 넉넉히 93일로 잡았다. (31일 x 3)
	 */
	'max_period_days' => 93,

	/*
	 * 줄 수를 어림할 때 쓰는 수집 간격(초).
	 * 5버전은 "기간(초) / 180 x 아이템 수" 로 줄 수를 어림했다. (3분마다 한 번 수집한다고 본 것)
	 * 실제 수집 간격이 다르면 이 값을 그 간격으로 바꾼다.
	 */
	'assumed_interval' => 180,

	/*
	 * 어림한 줄 수가 이 값을 넘으면 내보내지 않고 안내만 한다. (서버 메모리와 시간을 지키기 위한 한도)
	 * 5버전: 1000만 줄
	 */
	'max_rows' => 10000000,

	/*
	 * 파일 하나에 넣을 값 줄 수. 어림한 줄 수가 이 값을 넘으면 이 줄 수마다 CSV 를 나눠 zip 하나로 받는다.
	 * 5버전: export_csv.sh 의 split -l 1000000 (100만 줄마다 파일을 나눔)
	 * 엑셀은 한 시트에 1,048,576 줄까지 열 수 있어서, 100만 줄이면 파일 하나를 엑셀로 열 수 있다.
	 */
	'split_rows' => 1000000,

	/*
	 * "업무시간" 을 고르면 이 시간대의 값만 내보낸다. [시작 시, 끝 시]. 끝 시는 포함하지 않는다.
	 * 5버전: 9시 이상 18시 미만 (화면 문구 "업무시간 (09:00 ~ 18:00)")
	 * 시간대는 로그인한 사용자의 시간대 설정을 따른다. (5버전은 DB 서버의 시간대였다)
	 */
	'business_hours' => [9, 18]
];
